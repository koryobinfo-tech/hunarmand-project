def detect_topic(text: str, has_image: bool) -> Topic:
    t = (text or "").lower()
    best, score = TOPICS[0], 0
    for topic in TOPICS:
        hits = sum(1 for k in topic.keywords if k in t)
        if hits > score:
            best, score = topic, hits
    if score == 0 and has_image:
        return next(x for x in TOPICS if x.id == "chakan")
    if score == 0:
        return next(x for x in TOPICS if x.id == "care")
    return best


def build_reply(message: str, image_url: str | None) -> tuple[Topic, str]:
    topic = detect_topic(message, bool(image_url))
    intro = ""
    if image_url:
        intro = (
            "Сурати шуморо аз нигоҳи фарҳанги тоҷик дидем. Агар нақшҳои гулу барг бошанд — эҳтимолан чакан ё адрас; "
            "агар хатҳои кандакорӣ — чӯбкорӣ; агар ранги кабуди зарф — кулолгарӣ. "
        )
    if not (message or "").strip() and image_url:
        body = intro + topic.article
    else:
        body = intro + topic.article
        msg = (message or "").strip()
        if msg:
            body += f"\n\nДар робита ба саволи шумо («{msg[:160]}»): маслиҳати амалӣ — аз каталог намуна бинед ё фармоиши махсус диҳед, то андоза ва ранг дақиқ шавад."
    return topic, body


def related_products(db: Session, topic: Topic, limit: int = 4) -> list[dict]:
    q = db.query(Product)
    like_terms = topic.keywords[:4]
    from sqlalchemy import or_

    filters = [Product.title.ilike(f"%{k}%") | Product.description.ilike(f"%{k}%") for k in like_terms]
    if filters:
        rows = q.filter(or_(*filters)).limit(limit).all()
    else:
        rows = q.limit(limit).all()
    if len(rows) < 2:
        rows = db.query(Product).order_by(Product.created_at.desc()).limit(limit).all()
    return [
        {
            "id": p.id,
            "title": p.title,
            "price": p.price,
            "image": (p.images or [None])[0],
        }
        for p in rows
    ]


def topics_payload() -> list[dict]:
    return [{"id": t.id, "title": t.title, "prompt": t.prompt} for t in TOPICS]
